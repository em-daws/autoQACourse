    public static void example1() {
        Integer[] intArray = new Integer[5]; // Масив обгорток над типом int

        intArray[0] = 10; // Автобоксинг: примітивний int перетворюється в Integer
        intArray[1] = 20;
        intArray[2] = Integer.valueOf(30); // Інший спосіб додавання значення в масив
        intArray[3] = null; // Можна також зберігати null

        // Отримання значень з масиву обгорток
        int value = intArray[1]; // Анбоксинг: Integer перетворюється в примітивний int
        System.out.println(value); // Виведе: 20
    }

